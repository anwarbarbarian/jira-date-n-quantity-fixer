'use strict';

importScripts(
  'lib/timing.js',
  'lib/dom-utils.js',
  'lib/settings-utils.js'
);

const {
  DEFAULT_SETTINGS,
  COMPARISON_RULE,
  sanitiseSettings
} = globalThis.JiraValidator;

const TIMING = Object.freeze({
  PRE_ANALYSIS_SETTLE_MS: globalThis.JiraValidator.PRE_ANALYSIS_SETTLE_MS,
  STABLE_SAMPLE_COUNT: globalThis.JiraValidator.STABLE_SAMPLE_COUNT,
  TAB_STABLE_POLL_MS: globalThis.JiraValidator.TAB_STABLE_POLL_MS,
  MESSAGE_RETRY_BASE_MS: globalThis.JiraValidator.MESSAGE_RETRY_BASE_MS
});

const CONTENT_SCRIPT_FILES = Object.freeze([
  'lib/timing.js',
  'lib/dom-utils.js',
  'lib/date-utils.js',
  'lib/aem-utils.js',
  'lib/settings-utils.js',
  'lib/input-writer.js',
  'content/bootstrap.js',
  'content/page-readiness.js',
  'content/field-finders.js',
  'content/jira-ui-actions.js',
  'content/analyse-ticket.js',
  'content.js'
]);

const BASE_URL = 'https://jira.secext.samsung.net/browse/';
const STATE_KEY = 'jiraValidationState';
const ALARM_PREFIX = 'jira-validator-timeout-';
const DASHBOARD_PAGE = 'dashboard.html';

const DEFAULT_STATE = Object.freeze({
  running: false,
  stopRequested: false,
  queue: [],
  ticketInputText: '',
  currentIndex: 0,
  currentTicket: null,
  currentTabId: null,
  currentStage: null,
  currentRetryCount: 0,
  results: [],
  settings: null,
  startedAt: null,
  completedAt: null,
  lastMessage: 'Ready'
});

let transitionLock = false;

chrome.runtime.onInstalled.addListener(async (details) => {
  const stored = await chrome.storage.local.get(STATE_KEY);
  const existingState = stored[STATE_KEY];

  if (!existingState) {
    await saveState({ ...DEFAULT_STATE });
    return;
  }

  if (details.reason === 'update') {
    // Results generated by an older comparison implementation must not remain
    // visible after an upgrade, otherwise they can be mistaken for new output.
    await cleanupCurrentTab(existingState);
    await saveState({
      ...DEFAULT_STATE,
      settings: { ...DEFAULT_SETTINGS },
      lastMessage: `Updated to version ${chrome.runtime.getManifest().version}. Run validation again.`
    });
  }
});

chrome.runtime.onStartup.addListener(() => {
  void recoverValidationRun();
});

chrome.action.onClicked.addListener(() => {
  void chrome.tabs.create({ url: chrome.runtime.getURL(DASHBOARD_PAGE) });
});

chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  void handleMessage(message, sender)
    .then(sendResponse)
    .catch((error) => sendResponse({ ok: false, error: normaliseError(error) }));
  return true;
});

chrome.tabs.onUpdated.addListener((tabId, changeInfo) => {
  if (changeInfo.status !== 'complete') return;
  void handleTabReady(tabId);
});

chrome.tabs.onRemoved.addListener((tabId) => {
  void handleUnexpectedTabClose(tabId);
});

chrome.alarms.onAlarm.addListener((alarm) => {
  if (!alarm.name.startsWith(ALARM_PREFIX)) return;
  const tabId = Number(alarm.name.slice(ALARM_PREFIX.length));
  if (Number.isInteger(tabId)) {
    void handleTicketTimeout(tabId);
  }
});

async function recoverValidationRun() {
  const state = await getState();
  if (!state.running) return;

  if (state.currentTabId !== null) {
    try {
      const tab = await chrome.tabs.get(state.currentTabId);
      const recovered = {
        ...state,
        currentStage: 'loading',
        lastMessage: `Resuming ${state.currentTicket} after Chrome restarted.`
      };
      await saveState(recovered);
      chrome.alarms.create(`${ALARM_PREFIX}${state.currentTabId}`, {
        delayInMinutes: Math.max(2.5, (recovered.settings.timeoutSeconds + 90) / 60)
      });
      if (tab.status === 'complete') {
        await handleTabReady(state.currentTabId);
      }
      return;
    } catch {
      const recovered = {
        ...state,
        currentTabId: null,
        currentTicket: null,
        currentStage: null,
        lastMessage: 'Resuming validation after Chrome restarted.'
      };
      await saveState(recovered);
    }
  }

  await processNextTicket();
}

async function handleMessage(message, sender) {
  switch (message?.type) {
    case 'START_VALIDATION':
      return startValidation(message.payload);
    case 'STOP_VALIDATION':
      return stopValidation();
    case 'CLEAR_RESULTS':
      return clearResults();
    case 'SAVE_TICKET_INPUT':
      return saveTicketInput(message.payload);
    case 'GET_STATE':
      return { ok: true, state: await getState() };
    case 'EXECUTE_JIRA_MAIN_WORLD':
      return executeJiraMainWorldAction(sender, message.payload);
    default:
      return { ok: false, error: 'Unknown extension message.' };
  }
}


async function executeJiraMainWorldAction(sender, payload) {
  const tabId = sender?.tab?.id;
  if (!Number.isInteger(tabId)) {
    return { ok: false, error: 'The Jira tab could not be identified for the MAIN-world action.' };
  }

  try {
    await chrome.scripting.executeScript({
      target: { tabId },
      files: ['lib/input-writer.js'],
      world: 'MAIN'
    });
  } catch {
    // The shared writer may already be present in the page MAIN world.
  }

  const results = await chrome.scripting.executeScript({
    target: { tabId },
    world: 'MAIN',
    func: jiraMainWorldAction,
    args: [payload || {}]
  });

  return {
    ok: true,
    result: results?.[0]?.result || { success: true, message: 'MAIN-world action completed.' }
  };
}

function jiraMainWorldAction(payload) {
  const token = String(payload?.token || '');
  const action = String(payload?.action || '');

  if (action === 'GET_PAGE_STATE') {
    const bodyText = String(document.body?.innerText || document.body?.textContent || '')
      .replace(/\s+/g, ' ')
      .trim();
    const title = String(document.title || '');
    const lower = `${title} ${bodyText.slice(0, 5000)}`.toLowerCase();
    const deadLink = lower.includes("oops, you've found a dead link") ||
      lower.includes('oops, you’ve found a dead link') ||
      (/\bdead link\b/.test(lower) && lower.includes('jira'));
    const issueMatch = location.pathname.match(/\/browse\/([A-Z][A-Z0-9_]+-\d+)/i);
    const expectedTicket = String(payload?.ticket || '').toUpperCase();
    const detectedTicket = issueMatch?.[1]?.toUpperCase() || '';
    const issueShell = Boolean(document.querySelector(
      '#issue-content, #summary-val, #key-val, #due-date, #customfield_16801-val, #customfield_14002-val'
    ));

    return {
      success: true,
      ready: document.readyState === 'complete' && Boolean(document.body) && !deadLink,
      documentReadyState: document.readyState,
      ajsReady: Boolean(window.AJS),
      jiraReady: Boolean(window.JIRA),
      issueShell,
      deadLink,
      expectedTicket,
      detectedTicket,
      url: location.href,
      title
    };
  }

  const input = token
    ? document.querySelector(`[data-jira-validator-token="${token.replace(/[^a-zA-Z0-9_-]/g, '')}"]`)
    : null;

  if (!input) {
    return { success: false, message: 'The marked Jira input was not found in Jira MAIN world.' };
  }

  if (action === 'SET_INPUT_VALUE') {
    const value = String(payload?.value || '');
    const writer = globalThis.JiraValidatorInputWriter;
    if (writer?.prepareLiveDateInputForEdit) writer.prepareLiveDateInputForEdit(input);
    const observed = writer.writeInputValue(input, value, { useAjs: true });
    return {
      success: observed === value.trim(),
      message: `Replaced Jira input value with “${observed}” in MAIN world.`
    };
  }

  if (action === 'SUBMIT_EDIT_FORM') {
    const form = input.form || input.closest('form');
    if (!form) {
      return { success: false, message: 'The Quantity input was not inside a Jira edit form.' };
    }

    const submitter = form.querySelector(
      '#edit-issue-submit:not([disabled]), button[name="Update"]:not([disabled]), input[name="Update"]:not([disabled]), button[type="submit"]:not([disabled]), input[type="submit"]:not([disabled]), .aui-button-primary:not([disabled])'
    );

    try {
      if (typeof form.requestSubmit === 'function') {
        const validSubmitter = (
          submitter instanceof HTMLButtonElement || submitter instanceof HTMLInputElement
        ) && submitter.form === form && String(submitter.type || 'submit').toLowerCase() === 'submit';
        if (validSubmitter) form.requestSubmit(submitter);
        else form.requestSubmit();
        return { success: true, message: 'Submitted Jira Edit Issue form with requestSubmit().' };
      }

      if (submitter instanceof HTMLElement) {
        submitter.click();
        return { success: true, message: 'Submitted Jira Edit Issue form by clicking its submit control.' };
      }

      const event = new Event('submit', { bubbles: true, cancelable: true });
      const accepted = form.dispatchEvent(event);
      if (accepted) form.submit();
      return { success: true, message: 'Submitted Jira Edit Issue form using the submit event fallback.' };
    } catch (error) {
      return {
        success: false,
        message: error instanceof Error ? error.message : String(error)
      };
    }
  }

  if (action === 'COMMIT_INLINE_EDIT') {
    try {
      if (window.AJS?.$) {
        window.AJS.$(input).trigger('change').trigger('blur');
      }
    } catch {
      // Continue with native blur and Jira event.
    }

    input.dispatchEvent(new FocusEvent('focusout', {
      bubbles: true,
      composed: true,
      relatedTarget: document.body
    }));
    input.blur();

    let jiraEventTriggered = false;
    try {
      if (window.JIRA?.trigger && window.JIRA?.Events?.INLINE_EDIT_BLURRED) {
        window.JIRA.trigger(window.JIRA.Events.INLINE_EDIT_BLURRED, [payload?.fieldId || 'due-date']);
        jiraEventTriggered = true;
      }
    } catch {
      // Native blur still provides the normal Jira save-on-blur path.
    }

    return {
      success: true,
      message: jiraEventTriggered
        ? 'Triggered Jira INLINE_EDIT_BLURRED and native blur.'
        : 'Triggered native and AJS blur; Jira INLINE_EDIT_BLURRED was unavailable.'
    };
  }

  return { success: false, message: `Unsupported MAIN-world action: ${action}` };
}

async function startValidation(payload) {
  const tickets = Array.isArray(payload?.tickets) ? payload.tickets : [];
  const settings = sanitiseSettings(payload?.settings);

  if (!tickets.length) {
    return { ok: false, error: 'No valid Jira ticket IDs were supplied.' };
  }

  const previous = await getState();
  if (previous.running) {
    return { ok: false, error: 'A validation run is already in progress.' };
  }

  await cleanupCurrentTab(previous);

  const ticketInputText = String(
    payload?.ticketInputText ?? payload?.ticketInput ?? tickets.join('\n')
  );

  const state = {
    ...DEFAULT_STATE,
    running: true,
    queue: tickets,
    ticketInputText,
    settings,
    startedAt: new Date().toISOString(),
    lastMessage: `Starting validation for ${tickets.length} ticket(s).`
  };

  await saveState(state);
  await processNextTicket();
  return { ok: true, state: await getState() };
}

async function stopValidation() {
  const state = await getState();
  if (!state.running && !state.currentTabId) {
    return { ok: true, state };
  }

  const updated = {
    ...state,
    running: false,
    stopRequested: true,
    completedAt: new Date().toISOString(),
    lastMessage: 'Validation stopped by the user.'
  };
  await saveState(updated);
  await cleanupCurrentTab(updated);

  const finalState = {
    ...updated,
    currentTicket: null,
    currentTabId: null,
    currentStage: null
  };
  await saveState(finalState);
  return { ok: true, state: finalState };
}

async function clearResults() {
  const state = await getState();
  if (state.running) {
    return { ok: false, error: 'Stop the active validation before clearing results.' };
  }
  const cleared = {
    ...DEFAULT_STATE,
    settings: state.settings ? { ...state.settings } : null
  };
  await saveState(cleared);
  return { ok: true, state: cleared };
}

async function saveTicketInput(payload) {
  const state = await getState();
  if (state.running) {
    return { ok: true, state };
  }

  const ticketInputText = String(payload?.ticketInputText ?? '');
  const updated = {
    ...state,
    ticketInputText
  };
  await saveState(updated);
  return { ok: true, state: updated };
}

async function processNextTicket() {
  if (transitionLock) return;
  transitionLock = true;
  let continueAfterUnlock = false;

  try {
    const state = await getState();
    if (!state.running || state.currentTabId !== null) return;

    if (state.currentIndex >= state.queue.length) {
      await saveState({
        ...state,
        running: false,
        completedAt: new Date().toISOString(),
        lastMessage: `Completed ${state.results.length} ticket(s).`
      });
      return;
    }

    const ticket = state.queue[state.currentIndex];
    const url = `${BASE_URL}${encodeURIComponent(ticket)}`;
    const tab = await chrome.tabs.create({ url, active: false });

    const nextState = {
      ...state,
      currentTicket: ticket,
      currentTabId: tab.id,
      currentStage: 'loading',
      currentRetryCount: 0,
      lastMessage: `Loading ${ticket} (${state.currentIndex + 1}/${state.queue.length})...`
    };
    await saveState(nextState);

    chrome.alarms.create(`${ALARM_PREFIX}${tab.id}`, {
      delayInMinutes: Math.max(2.5, (nextState.settings.timeoutSeconds + 90) / 60)
    });

    const latestTab = await chrome.tabs.get(tab.id);
    if (latestTab.status === 'complete') {
      void handleTabReady(tab.id);
    }
  } catch (error) {
    const state = await getState();
    await appendFailureAndAdvance(
      state,
      'EXTENSION_ERROR',
      normaliseError(error),
      false
    );
    continueAfterUnlock = state.running;
  } finally {
    transitionLock = false;
  }

  if (continueAfterUnlock) {
    await processNextTicket();
  }
}

async function handleTabReady(tabId) {
  const state = await getState();
  if (!state.running || state.currentTabId !== tabId || state.currentStage !== 'loading') {
    return;
  }

  await saveState({
    ...state,
    currentStage: 'settling',
    lastMessage: `Waiting for ${state.currentTicket} to finish rendering...`
  });

  try {
    let navigation = await waitForStableTicketTab(
      tabId,
      state.currentTicket,
      Math.min(state.settings.timeoutSeconds * 1000, 30000)
    );

    // A complete event may belong to an SSO/intermediate page. If it never
    // settles on the requested issue, make one controlled canonical retry.
    if (!navigation.ready && !navigation.authenticationPage) {
      const retryUrl = `${BASE_URL}${encodeURIComponent(state.currentTicket)}?jiraValidatorRetry=${Date.now()}`;
      await chrome.tabs.update(tabId, { url: retryUrl });
      navigation = await waitForStableTicketTab(
        tabId,
        state.currentTicket,
        Math.min(state.settings.timeoutSeconds * 1000, 30000)
      );
    }

    if (!navigation.ready && !navigation.authenticationPage) {
      throw new Error(navigation.message || `Jira did not settle on ${state.currentTicket}.`);
    }

    const latestState = await getState();
    if (!latestState.running || latestState.currentTabId !== tabId) return;

    await saveState({
      ...latestState,
      currentStage: 'analysing',
      lastMessage: `Analysing ${latestState.currentTicket}...`
    });

    // Jira Data Center can fire the browser complete event before AJS has
    // attached inline-edit and Edit Issue handlers. Give the app one final
    // short settle window before the content script performs any action.
    await sleep(TIMING.PRE_ANALYSIS_SETTLE_MS);

    const response = await sendAnalysisMessageWithRetry(tabId, {
      type: 'ANALYSE_JIRA_TICKET',
      payload: {
        ticket: latestState.currentTicket,
        settings: latestState.settings
      }
    });

    if (!response?.ok) {
      throw new Error(response?.error || 'The Jira page analyser returned no result.');
    }

    await completeCurrentTicket(tabId, response.result);
  } catch (error) {
    const latestState = await getState();
    if (latestState.currentTabId !== tabId) return;
    await appendFailureAndAdvance(latestState, 'ANALYSIS_ERROR', normaliseError(error));
  }
}

async function waitForStableTicketTab(tabId, ticket, timeoutMs) {
  const started = Date.now();
  let stableSamples = 0;
  let lastUrl = '';
  let lastStatus = '';
  let lastMessage = '';

  while (Date.now() - started < timeoutMs) {
    let tab;
    try {
      tab = await chrome.tabs.get(tabId);
    } catch {
      return { ready: false, authenticationPage: false, message: 'The Jira tab was closed while loading.' };
    }

    const url = String(tab.url || '');
    const complete = tab.status === 'complete';
    const expected = isExpectedTicketUrl(url, ticket);
    const authenticationPage = isAuthenticationUrl(url);

    if (complete && (expected || authenticationPage)) {
      const signature = `${url}|${tab.status}`;
      if (signature === `${lastUrl}|${lastStatus}`) stableSamples += 1;
      else stableSamples = 1;
      lastUrl = url;
      lastStatus = tab.status;

      if (stableSamples >= TIMING.STABLE_SAMPLE_COUNT) {
        return { ready: expected, authenticationPage, url, message: '' };
      }
    } else {
      stableSamples = 0;
      lastUrl = url;
      lastStatus = tab.status || '';
      lastMessage = url
        ? `Jira was still on ${url}.`
        : 'Jira had not assigned a final URL yet.';
    }

    await sleep(TIMING.TAB_STABLE_POLL_MS);
  }

  return {
    ready: false,
    authenticationPage: isAuthenticationUrl(lastUrl),
    url: lastUrl,
    message: lastMessage || `Jira did not finish loading ${ticket} within the readiness window.`
  };
}

function isExpectedTicketUrl(rawUrl, ticket) {
  try {
    const url = new URL(rawUrl);
    if (url.hostname.toLowerCase() !== 'jira.secext.samsung.net') return false;
    const match = url.pathname.match(/\/browse\/([A-Z][A-Z0-9_]+-\d+)/i);
    return match?.[1]?.toUpperCase() === String(ticket || '').toUpperCase();
  } catch {
    return false;
  }
}

function isAuthenticationUrl(rawUrl) {
  try {
    const url = new URL(rawUrl);
    const value = `${url.pathname}${url.search}`.toLowerCase();
    return value.includes('/login') || value.includes('login.jsp') || value.includes('os_destination');
  } catch {
    return false;
  }
}

async function sendAnalysisMessageWithRetry(tabId, message) {
  let lastError;

  for (let attempt = 1; attempt <= 5; attempt += 1) {
    try {
      return await chrome.tabs.sendMessage(tabId, message);
    } catch (error) {
      lastError = error;
      if (attempt === 2) {
        try {
          await chrome.scripting.executeScript({
            target: { tabId },
            files: [...CONTENT_SCRIPT_FILES]
          });
        } catch {
          // A static content script may already exist; retrying the message is enough.
        }
      }
      await sleep(attempt * TIMING.MESSAGE_RETRY_BASE_MS);
    }
  }

  throw lastError || new Error('Could not connect to the Jira page.');
}

async function completeCurrentTicket(tabId, result) {
  const state = await getState();
  if (state.currentTabId !== tabId) return;

  const retryableErrors = new Set([
    'DEAD_LINK',
    'DEAD_LINK_DURING_UPDATE',
    'PAGE_NOT_READY',
    'NAVIGATION_MISMATCH'
  ]);
  const retryCount = Number.isInteger(state.currentRetryCount) ? state.currentRetryCount : 0;

  if (retryableErrors.has(result?.errorCode) && retryCount < 1) {
    const retryUrl = `${BASE_URL}${encodeURIComponent(state.currentTicket)}?jiraValidatorRetry=${Date.now()}`;
    await saveState({
      ...state,
      currentStage: 'loading',
      currentRetryCount: retryCount + 1,
      lastMessage: `${state.currentTicket}: transient Jira navigation error; retrying once...`
    });
    chrome.alarms.create(`${ALARM_PREFIX}${tabId}`, {
      delayInMinutes: Math.max(2.5, (state.settings.timeoutSeconds + 90) / 60)
    });
    await chrome.tabs.update(tabId, { url: retryUrl });
    return;
  }

  const enrichedResult = {
    ticket: state.currentTicket,
    url: `${BASE_URL}${encodeURIComponent(state.currentTicket)}`,
    ...result,
    processedAt: new Date().toISOString()
  };

  const nextState = {
    ...state,
    results: [...state.results, enrichedResult],
    currentIndex: state.currentIndex + 1,
    currentTicket: null,
    currentTabId: null,
    currentStage: null,
    currentRetryCount: 0,
    lastMessage: `${state.currentTicket}: ${formatResultStatus(enrichedResult)}`
  };

  await chrome.alarms.clear(`${ALARM_PREFIX}${tabId}`);
  await saveState(nextState);
  await closeTabSafely(tabId);
  await processNextTicket();
}

async function appendFailureAndAdvance(state, errorCode, errorMessage, processNext = true) {
  const tabId = state.currentTabId;
  if (tabId !== null) {
    await chrome.alarms.clear(`${ALARM_PREFIX}${tabId}`);
  }

  const result = {
    ticket: state.currentTicket || state.queue[state.currentIndex] || 'Unknown',
    url: state.currentTicket ? `${BASE_URL}${encodeURIComponent(state.currentTicket)}` : '',
    originalDueDateRaw: '',
    originalDueDateIso: '',
    dueDateRaw: '',
    liveDateRaw: '',
    dueDateIso: '',
    liveDateIso: '',
    dateStatus: 'ERROR',
    dateMessage: errorMessage,
    comparisonRule: COMPARISON_RULE,
    dueUpdateAttempted: false,
    dueUpdateSuccess: false,
    dueUpdateStatus: 'NOT_ATTEMPTED',
    dueUpdateTargetIso: '',
    dueUpdateSubmittedValue: '',
    dueUpdateMessage: '',
    issueLabels: [],
    aemPagePathCount: 0,
    aemPagePathLines: [],
    quantityLabelBonus: 0,
    quantityExpected: null,
    originalQuantityRaw: '',
    originalQuantity: null,
    quantityRaw: '',
    quantity: null,
    quantityStatus: 'ERROR',
    quantityMessage: errorMessage,
    quantityUpdateAttempted: false,
    quantityUpdateSuccess: false,
    quantityUpdateStatus: 'NOT_ATTEMPTED',
    quantityUpdateTarget: null,
    quantityUpdateSubmittedValue: '',
    quantityUpdateMessage: '',
    errorCode,
    errorMessage,
    processedAt: new Date().toISOString()
  };

  const nextState = {
    ...state,
    results: [...state.results, result],
    currentIndex: state.currentIndex + 1,
    currentTicket: null,
    currentTabId: null,
    currentStage: null,
    currentRetryCount: 0,
    lastMessage: `${result.ticket}: ${errorCode}`
  };

  await saveState(nextState);
  if (tabId !== null) {
    await closeTabSafely(tabId);
  }
  if (nextState.running && processNext) {
    await processNextTicket();
  }
}

async function handleTicketTimeout(tabId) {
  const state = await getState();
  if (!state.running || state.currentTabId !== tabId) return;
  await appendFailureAndAdvance(
    state,
    'TIMEOUT',
    `The ticket did not finish loading within ${state.settings.timeoutSeconds} seconds.`
  );
}

async function handleUnexpectedTabClose(tabId) {
  const state = await getState();
  if (!state.running || state.currentTabId !== tabId) return;
  await appendFailureAndAdvance(
    state,
    'TAB_CLOSED',
    'The Jira validation tab was closed before analysis completed.'
  );
}

async function cleanupCurrentTab(state) {
  if (state.currentTabId === null || state.currentTabId === undefined) return;
  await chrome.alarms.clear(`${ALARM_PREFIX}${state.currentTabId}`);
  await closeTabSafely(state.currentTabId);
}

async function closeTabSafely(tabId) {
  try {
    await chrome.tabs.remove(tabId);
  } catch {
    // The user or browser may already have closed the tab.
  }
}

function formatResultStatus(result) {
  const date = result?.dueUpdateStatus === 'UPDATED' && result?.dateStatus === 'PASS'
    ? 'Date PASS · UPDATED'
    : result?.dateStatus === 'SKIPPED'
      ? 'Date SKIPPED'
      : `Date ${result?.dateStatus || 'ERROR'}`;
  const quantity = result?.quantityUpdateStatus === 'UPDATED' && result?.quantityStatus === 'PASS'
    ? 'Quantity PASS · UPDATED'
    : result?.quantityStatus === 'SKIPPED'
      ? 'Quantity SKIPPED'
      : `Quantity ${result?.quantityStatus || 'ERROR'}`;
  return `${date}; ${quantity}`;
}

async function getState() {
  const stored = await chrome.storage.local.get(STATE_KEY);
  const state = { ...DEFAULT_STATE, ...(stored[STATE_KEY] || {}) };
  return {
    ...state,
    settings: state.settings ? sanitiseSettings(state.settings) : null
  };
}

async function saveState(state) {
  await chrome.storage.local.set({ [STATE_KEY]: state });
}

function sleep(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

function normaliseError(error) {
  if (error instanceof Error) return error.message;
  return String(error || 'Unknown error');
}
